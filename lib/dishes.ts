export function signatureDishes(cuisines: string[], craving?: string): string[] {
  const found: string[] = [];
  const keys = cuisines.map((c) => c.toLowerCase());
  
  for (const key of keys) {
    for (const [cKey, dishes] of Object.entries(DISHES_BY_CUISINE)) {
      if (key.includes(cKey) || cKey.includes(key)) {
        found.push(...dishes);
      }
    }
  }

  if (craving === "kabsa") found.unshift("كبسة دجاج شواية", "مندي لحم بلدي");
  if (craving === "sushi") found.unshift("سوشي رول كاليفورنيا", "ساشيمي سالمون");
  if (craving === "pizza") found.unshift("بيتزا نابوليتانا بالحطب", "باستا تروفل");
  if (craving === "burger") found.unshift("برجر لحم بلاك أنجوس", "سلايدرز دجاج");
  if (craving === "seafood") found.unshift("روبيان جامبو مشوي", "سمك هامور طازج");
  if (craving === "shawarma") found.unshift("شاورما صاج دجاج", "كباب شامي");
  if (craving === "grill") found.unshift("مشاوي مشكلة كباب وكفتة", "ستيك ريب آي");
  if (craving === "indian") found.unshift("برياني دجاج حيدر أباد", "دجاج تيكا ماسالا");
  if (craving === "cafe") found.unshift("فرنش توست مكرمل", "قهوة مختصة فلات وايت");

  const unique = [...new Set(found)];
  if (unique.length === 0) {
    return ["طبق الموسم المميز", "وجبة الشيف الخاصة", "المقبلات المشكلة"];
  }
  return unique.slice(0, 4);
}

